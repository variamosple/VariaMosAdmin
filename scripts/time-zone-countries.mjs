// cspell:ignore tzdata zoneinfo
// Writes src/shared/domain/timeZoneCountries.ts from the zone.tab file of
// the IANA time zone database (public domain), for the time zone search
// (EV-115). Run it when a new tzdata version changes the countries:
//   node scripts/time-zone-countries.mjs /usr/share/zoneinfo/zone.tab
import { readFileSync, writeFileSync } from "node:fs";

const [source = "/usr/share/zoneinfo/zone.tab"] = process.argv.slice(2);
const version =
  readFileSync(new URL("tzdata.zi", `file://${source}`), "utf8").match(
    /^# version (\S+)/,
  )?.[1] ?? "unknown";
const rows = readFileSync(source, "utf8")
  .split("\n")
  .filter((line) => line && !line.startsWith("#"))
  .map((line) => {
    const [country, , zone, region = ""] = line.split("\t");
    return `${country}|${zone}|${region}`;
  })
  .sort();

writeFileSync(
  new URL("../src/shared/domain/timeZoneCountries.ts", import.meta.url),
  `// cspell:disable
// Generated by scripts/time-zone-countries.mjs from zone.tab of the IANA
// time zone database ${version} (public domain): the country of each time
// zone, and the part of the country it covers when there are several.
// One line per zone: country code|time zone|part of the country.
export const ZONE_COUNTRIES = \`
${rows.join("\n")}
\`;
`,
);
console.log(`${rows.length} time zones, tzdata ${version}`);
